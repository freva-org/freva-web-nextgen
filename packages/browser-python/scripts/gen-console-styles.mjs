/**
 * Embed the vendor terminal stylesheet AND `src/console/styles.css` into a TypeScript module. Same
 * reasoning as `gen-python-sources.mjs`: a `.css` beside a `.ts` does not survive `tsc`, and the
 * stylesheet has to be a string to put inside a shadow root. `--check` fails the typecheck when the
 * two have drifted. A separate `console.css` is also published for light-DOM consumers.
 *
 * The vendor sheet comes FIRST, and this package's rules override it. Vendoring the whole sheet
 * rather than copying the rules the console needs costs a few KiB and removes a category of bug - a
 * hand-copied subset is missing whatever nobody noticed was needed, which is how a caret ends up
 * with no paint, no inversion and no `terminal-blink` keyframes. The public contract is still the
 * `--bp-*` custom properties and `::part()`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, "..", "src", "console", "styles.css");
const OUT = join(HERE, "..", "src", "console", "styles.generated.ts");
const VENDOR = join(
  HERE,
  "..",
  "..",
  "..",
  "node_modules",
  "jquery.terminal",
  "css",
  "jquery.terminal.min.css",
);

/**
 * Strip comments and collapse whitespace, WITHOUT touching anything inside a string or a url().
 * This output is embedded in the console bundle as a JavaScript string, so every byte of
 * `styles.css` is downloaded by every visitor, comments included: 35,785 bytes of authored CSS, a
 * little over a third of it prose. The prose stays in `src/console/styles.css`; what ships is the
 * rules.
 *
 * DELIBERATELY CONSERVATIVE: it removes comments and runs of whitespace and does NOT rewrite
 * selectors, merge rules, shorten colours or drop the last semicolon in a block.
 */
function trimCss(text) {
  let out = "";
  let quote = "";
  let inUrl = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quote) {
      out += ch;
      if (ch === "\\") {
        out += text[i + 1] ?? "";
        i += 1;
      } else if (ch === quote) quote = "";
      continue;
    }
    if (ch === '"' || ch === "'") {
      quote = ch;
      out += ch;
      continue;
    }
    if (!inUrl && ch === "/" && text[i + 1] === "*") {
      const end = text.indexOf("*/", i + 2);
      i = end === -1 ? text.length : end + 1;
      // A comment between two tokens becomes one space, so `a/*x*/b` cannot become `ab`.
      if (!/\s$/.test(out)) out += " ";
      continue;
    }
    if (/\s/.test(ch)) {
      if (!/\s$/.test(out)) out += " ";
      continue;
    }
    out += ch;
    if (!inUrl && /url\($/i.test(out)) inUrl = true;
    else if (inUrl && ch === ")") inUrl = false;
  }
  // Space is only meaningful between tokens, never beside these. NOTE WHAT IS NOT DONE: the space
  // BEFORE a colon is kept, because `.bp-terminal ::selection` is a descendant combinator followed
  // by a pseudo-element while `.bp-terminal::selection` is one on the terminal itself - and this
  // sheet contains exactly that selector, carrying the rule that keeps selected text from being
  // painted in transparent ink.
  return out
    .replace(/\s*([{};,])\s*/g, "$1")
    .replace(/;\}/g, "}")
    .replace(/:\s+/g, ":")
    .trim();
}

const vendor = readFileSync(VENDOR, "utf8");
const css =
  "/* vendored from jquery.terminal, pinned by the lockfile. Overridden below. */\n" +
  vendor +
  "\n" +
  trimCss(readFileSync(SRC, "utf8"));
const next =
  "// GENERATED by scripts/gen-console-styles.mjs from jquery.terminal's CSS + src/console/styles.css.\n" +
  "// Do not edit.\n" +
  "\n" +
  "/** The console's stylesheet, for insertion into the shadow root. */\n" +
  `export const CONSOLE_STYLES: string = ${JSON.stringify(css)};\n`;

let current = null;
try {
  current = readFileSync(OUT, "utf8");
} catch {
  /* not generated yet */
}

if (process.argv.includes("--check")) {
  if (current !== next) {
    console.error("styles.generated.ts is out of date with src/console/styles.css.");
    process.exit(1);
  }
  console.log("console styles.generated.ts is up to date");
} else if (current !== next) {
  writeFileSync(OUT, next);
  console.log(`console styles.generated.ts regenerated, ${css.length} bytes of CSS`);
} else {
  console.log("console styles.generated.ts is up to date");
}
