/**
 * Embed the vendor terminal stylesheet AND `src/console/styles.css` + `notice-card.css` into a
 * TypeScript module, and `src/display/display.css` + `notice-card.css` into another for rich
 * output (adopted lazily, with the renderer, and by the notebook kernel). Same
 * reasoning as `gen-python-sources.mjs`: a `.css` beside a `.ts` does not survive `tsc`, and the
 * stylesheet has to be a string to put inside a shadow root. `--check` fails the typecheck when the
 * two have drifted. A separate `console.css` is also published for light-DOM consumers.
 *
 * The vendor sheet comes FIRST, and this package's rules override it. Vendoring the whole sheet
 * rather than copying the rules the console needs costs a few KiB and removes a category of bug - a
 * hand-copied subset is missing whatever nobody noticed was needed, which is how a caret ends up
 * with no paint, no inversion and no `terminal-blink` keyframes. The public contract is still the
 * `--bp-*` custom properties and `::part()`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { trimCss } from "./trim-css.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, "..", "src", "console", "styles.css");
const NOTICE = join(HERE, "..", "src", "console", "notice-card.css");
const DISPLAY = join(HERE, "..", "src", "display", "display.css");
const OUT = join(HERE, "..", "src", "console", "styles.generated.ts");
const DISPLAY_OUT = join(HERE, "..", "src", "display", "styles.generated.ts");
const VENDOR = join(
  HERE,
  "..",
  "..",
  "..",
  "node_modules",
  "jquery.terminal",
  "css",
  "jquery.terminal.min.css",
);

const vendor = readFileSync(VENDOR, "utf8");
const css =
  "/* vendored from jquery.terminal, pinned by the lockfile. Overridden below. */\n" +
  vendor +
  "\n" +
  trimCss(readFileSync(SRC, "utf8")) +
  trimCss(readFileSync(NOTICE, "utf8"));
const next =
  "// GENERATED by scripts/gen-console-styles.mjs from jquery.terminal's CSS + src/console/styles.css.\n" +
  "// Do not edit.\n" +
  "\n" +
  "/** The console's stylesheet, for insertion into the shadow root. */\n" +
  `export const CONSOLE_STYLES: string = ${JSON.stringify(css)};\n`;

const displayNext =
  "// GENERATED by scripts/gen-console-styles.mjs from src/display/display.css and\n" +
  "// src/console/notice-card.css. Do not edit.\n" +
  "\n" +
  "/** Rich-output rules, scoped under `.fv-output`. See src/display/display.css. */\n" +
  `export const DISPLAY_STYLES: string = ${JSON.stringify(trimCss(readFileSync(DISPLAY, "utf8")))};\n` +
  "\n" +
  "/** The no-JSPI notice card's rules, shared with the console. */\n" +
  `export const NOTICE_CARD_STYLES: string = ${JSON.stringify(trimCss(readFileSync(NOTICE, "utf8")))};\n`;

let failed = false;
for (const [file, content, label] of [
  [OUT, next, "console styles.generated.ts"],
  [DISPLAY_OUT, displayNext, "display styles.generated.ts"],
]) {
  let current = null;
  try {
    current = readFileSync(file, "utf8");
  } catch {
    // not generated yet
  }
  if (process.argv.includes("--check")) {
    if (current !== content) {
      console.error(`${label} is out of date with its CSS sources.`);
      failed = true;
    } else console.log(`${label} is up to date`);
  } else if (current !== content) {
    writeFileSync(file, content);
    console.log(`${label} regenerated, ${content.length} bytes`);
  } else {
    console.log(`${label} is up to date`);
  }
}
if (failed) process.exit(1);
